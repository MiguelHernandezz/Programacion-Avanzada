    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
            // Verifica que estemos conectados al servicio antes de enviar la orden
            if (servicio != null) {
                // Llama al método remoto para pausar o reanudar el programa principal en el servidor
                servicio.conmutarPausa();
                // Actualiza la interfaz gráfica inmediatamente para reflejar el cambio en el botón
                actualizarUI();
            }
        } catch (java.rmi.RemoteException ex) {
            // Manejo de errores si falla la comunicación con el servidor al pulsar el botón
            System.err.println("No se pudo enviar la orden de pausa.");
        }
    }//GEN-LAST:event_jButton1ActionPerformed
    
    
    
    // Metodod para actualizar los datos
    // Metodod para actualizar los datos visuales de la interfaz
    private void actualizarUI() {
        // Si no hay conexión con el servidor, sale del método y no hace nada
        if (servicio == null) return;

        try {
            // Obtiene el total de niños y lo muestra en la etiqueta 2
            jLabel2.setText("Total niños en hawkings [" + servicio.getTotalNinosHawkins() + "]");
            // Obtiene los datos en formato HTML de portales, ubicaciones de niños y demogorgons
            jLabel8.setText("<html>" + servicio.getPortalesHTML() + "</html>");
            jLabel5.setText("<html>" + servicio.getUbicacionesNinosHTML() + "</html>");
            jLabel7.setText("<html>" + servicio.getUbicacionesDemosHTML() + "</html>");

            // Obtiene el ranking de demogorgons capturados
            String ranking = servicio.getRankingDemos();
            if (ranking != null) {
                // Reemplaza los saltos de línea de texto plano por etiquetas <br> de HTML para que se vea bien en el JLabel
                jLabel4.setText("<html>Ranking Demogorgons<br>Capturas:<br><br>" + ranking.replace("\n", "<br><br>") + "</html>");
            }

            // Obtiene la información sobre si hay algún evento global activo
            String evento = servicio.getEstadoEvento();
            if (evento != null) {
                // Formatea el texto del evento global de igual manera con etiquetas HTML
                jLabel1.setText("<html>Evento Global Activo:<br><br>" + evento.replace("\n", "<br><br>") + "</html>");
            }

            // boton Pausa: comprueba si el servidor está pausado actualmente
            if (servicio.isPausado()) {
                // Si está pausado, el botón ofrece la opción de reanudar
                jButton1.setText("Reanudar Programa Principal");
            } else {
                // Si está en marcha, el botón ofrece la opción de detener
                jButton1.setText("Detener Programa Principal");
            }

        } catch (Exception e) { 
            // Captura cualquier error de conexión o RMI durante la actualización de datos
            e.printStackTrace(); 
        }
    }
