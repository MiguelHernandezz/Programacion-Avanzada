    // Método auxiliar para formatear la información de un portal en una etiqueta (JLabel)
    private void actualizarTextoPortal(javax.swing.JLabel label, Portal p) {
        // Utiliza formato HTML para centrar el texto y hacer saltos de línea (<br>) dentro de la etiqueta
        // String.format inyecta los números de niños esperando, cruzando y volviendo en los %d correspondientes
        String texto = String.format("<html><center>Esperando: %d<br>Cruzando: %d<br>Vuelta: %d</center></html>", 
                                     p.getNinosEsperando(), 
                                     p.getNinosCruzando(),
                                     p.getEsperandoVuelta());
        // Aplica el texto formateado a la etiqueta visual
        label.setText(texto);
    }

    // Método auxiliar genérico para convertir las listas de Niños en texto separado por comas
    private String formatearLista(java.util.List<Nino> lista) {
        // Utiliza la API de Streams de Java para iterar la lista, extraer el ID de cada niño y unirlos con ", "
        return lista.stream().map(Nino::getIdNino).collect(java.util.stream.Collectors.joining(", "));
    }
    
    // Método auxiliar genérico para convertir las listas de Demogorgons en texto separado por comas
    private String formatearListaDemos(java.util.List<Demogorgon> lista) {
        // Hace lo mismo que el método anterior, pero extrayendo el ID de los Demogorgons
        return lista.stream().map(Demogorgon::getIdDemogorgon).collect(java.util.stream.Collectors.joining(", "));
    }
