    private String formatearPlaneta(federacion.monitores.Planeta p) {
        String colorEstado = p.isBajoAtaque() ? "red" : "green";
        String textoEstado = p.isBajoAtaque() ? "ATAQUE" : "Libre";
        return "<html><b>" + p.getNombre().toUpperCase() + "</b><br>" +
               "Delegados: " + p.getDelegadosPresentes() + " / 4<br>" +
               "Cola: " + p.getDelegadosEnCola() + "<br>" +
               "Patrullas: " + p.getPatrullasPresentes() + " / 3<br>" +
               "Estado: <span style='color:" + colorEstado + ";'>" + textoEstado + "</span></html>";
    }

    private String formatearDeposito(federacion.monitores.Deposito d) {
        String colorEstado = d.isBajoAtaque() ? "red" : "green";
        String textoEstado = d.isBajoAtaque() ? "ATAQUE" : "Libre";
        
        return "<html><b>" + d.getNombre() + "</b><br>" +
               "<span style=\"font-size: 1.5em;\">" + d.getCantidadAlmacenada() + " / " + d.getCapacidadMaxima() + "</span><br>" +
               "Depositando: " + d.getDelegadosPresentes() + " / 3<br>" +
               "Esperando: " + d.getDelegadosEnCola() + "<br>" +
               "Patrullas: " + d.getPatrullasPresentes() + " / 3<br>" +
               "Estado: <span style='color:" + colorEstado + ";'><b>" + textoEstado + "</b></span></html>";
    }
