    private void conectarAlServidor() {
        try {
            Registry registry = LocateRegistry.getRegistry(HOST, PUERTO);
            servidor = (FederacionRemota) registry.lookup("FederacionGalactica");
            System.out.println("Conectado al servidor RMI correctamente.");
        } catch (Exception e) {
            System.err.println("Error al conectar con el servidor RMI: " + e.getMessage());
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No se puede conectar al servidor RMI en " + HOST + ":" + PUERTO +
                    "\nAsegúrese de que el servidor está en ejecución.",
                    "Error de conexión", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

    
    private void iniciarActualizacionAutomatica() {
        javax.swing.Timer timer = new javax.swing.Timer(100, e -> actualizarInterfaz());
        timer.start();
    }

